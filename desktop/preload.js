// The only bridge between pages and the app: a small, fixed set of calls.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

const on = (ch) => (cb) => { const h = (_e, v) => cb(v); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };
contextBridge.exposeInMainWorld('sd', {
  platform: process.platform,
  get: () => ipcRenderer.invoke('settings:get'),
  set: (patch) => ipcRenderer.invoke('settings:set', patch),
  paused: () => ipcRenderer.invoke('paused'),
  stats: () => ipcRenderer.invoke('stats'),
  weather: (city) => ipcRenderer.invoke('weather', city),
  books: (q) => ipcRenderer.invoke('books', q),
  openPlace: (key) => ipcRenderer.invoke('places:open', key),
  apps: () => ipcRenderer.invoke('apps'),
  appIcon: (p) => ipcRenderer.invoke('app-icon', p),
  launch: (p) => ipcRenderer.invoke('launch', p),
  open: (url) => ipcRenderer.invoke('open', url),
  pickFile: (kind) => ipcRenderer.invoke('pick-file', kind),
  toggleHome: (show, mode) => ipcRenderer.invoke('home:toggle', show, mode),
  battery: () => ipcRenderer.invoke('battery'),
  timer: (action, arg) => (action ? ipcRenderer.invoke('timer', action, arg) : ipcRenderer.invoke('timer:get')),
  onTimer: on('timer'),
  gamer: (on) => ipcRenderer.invoke('gamer', on),
  switchTest: () => ipcRenderer.invoke('switch:test'),
  switchStatus: () => ipcRenderer.invoke('switch:status'),
  topbarTimer: () => ipcRenderer.invoke('topbar:timer'),
  flyout: (panel, x, data) => ipcRenderer.invoke('flyout:open', panel, x, data),
  flyoutData: () => ipcRenderer.invoke('flyout:data'),
  thumbs: (rects) => ipcRenderer.invoke('thumbs', rects),
  flyoutAction: (what) => ipcRenderer.invoke('flyout:action', what),
  flyoutState: () => ipcRenderer.invoke('flyout:state'),
  onFlyout: on('flyout'),
  flyoutPanel: () => ipcRenderer.invoke('flyout:panel'),
  flyoutReady: () => ipcRenderer.send('flyout:ready'),
  sys: () => ipcRenderer.invoke('sys:get'),
  setSys: (what, value) => ipcRenderer.invoke('sys:set', what, value),
  appIcons: () => ipcRenderer.invoke('sys:appIcons'),
  onSys: on('sys'),
  onIme: on('ime'),
  ime: () => ipcRenderer.invoke('ime:get'),
  bin: () => ipcRenderer.invoke('bin:get'),
  onBin: on('bin'),
  openBin: () => ipcRenderer.invoke('bin:open'),
  emptyBin: () => ipcRenderer.invoke('bin:empty'),
  trashFiles: (files) => ipcRenderer.invoke('bin:trash', [...files].map((f) => webUtils.getPathForFile(f)).filter(Boolean)), // files dropped on the Bin
  shots: () => ipcRenderer.invoke('shots:list'),
  onShots: on('shots'),
  openShot: (p) => ipcRenderer.invoke('shots:open', p),
  shotsFolder: () => ipcRenderer.invoke('shots:folder'),
  takeShot: () => ipcRenderer.invoke('shots:take'),
  dragShot: (p) => ipcRenderer.send('shots:drag', p),
  dockOpenWith: (target, files) => ipcRenderer.invoke('dock:openWith', target, [...files].map((f) => webUtils.getPathForFile(f)).filter(Boolean)), // files dropped on a dock app
  onOsd: on('osd'),
  wifiList: (scan) => ipcRenderer.invoke('net:wifi', scan),
  wifiConnect: (ssid, password, secure) => ipcRenderer.invoke('net:connect', ssid, password, secure),
  power: () => ipcRenderer.invoke('power:get'),
  setPower: (what, value) => ipcRenderer.invoke('power:set', what, value),
  topbarDesk: (i) => ipcRenderer.invoke('topbar:desk', i),
  onIslandOpen: on('island-open'),
  onGamer: on('gamer'),
  islandMouse: (inside) => ipcRenderer.send('island:mouse', !!inside),
  islandSize: (expanded) => ipcRenderer.send('island:size', !!expanded),
  openSettings: () => ipcRenderer.invoke('settings:open'),
  taskbar: () => ipcRenderer.invoke('taskbar:get'),
  setTaskbar: (patch) => ipcRenderer.invoke('taskbar:set', patch),
  gestures: () => ipcRenderer.invoke('gestures:get'),
  macGestures: () => ipcRenderer.invoke('gestures:mac'),
  applyLockScreen: () => ipcRenderer.invoke('lock:apply'),
  windowsSettings: (page) => ipcRenderer.invoke('windows-settings', page),
  windows: () => ipcRenderer.invoke('windows'),
  focusWindow: (hwnd, toggle) => ipcRenderer.invoke('window:focus', hwnd, toggle),
  closeWindow: (hwnd) => ipcRenderer.invoke('window:close', hwnd),
  newWindow: (exe) => ipcRenderer.invoke('window:new', exe),
  exeIcon: (exe) => ipcRenderer.invoke('exe-icon', exe),
  pinTarget: (p) => ipcRenderer.invoke('pin-target', p),
  diagnostics: () => ipcRenderer.invoke('diagnostics'),
  media: () => ipcRenderer.invoke('media:get'),
  mediaControl: (cmd, app) => ipcRenderer.invoke('media:control', cmd, app),
  onMedia: on('media'),
  onPower: on('power'),
  dockMouse: (inside) => ipcRenderer.send('dock:mouse', !!inside),
  dockKeys: (what) => ipcRenderer.invoke('dock:keys', what),
  onDockShown: on('dock-shown'),
  dockState: () => ipcRenderer.invoke('dock:state'),
  switchApp: (dir) => ipcRenderer.invoke('switch-app', dir),
  onTopbar: on('topbar'),
  onWindows: on('windows'),
  onSettings: on('settings'),
  onPause: on('pause'),
  onDeskSlide: on('desk-slide'),
  onWpDesk: on('wp-desk'),
  trayList: () => ipcRenderer.invoke('tray:list'),
  trayClick: (id, kind, x, y) => ipcRenderer.invoke('tray:click', id, kind, x, y),
  onTray: on('tray'),
  overview: () => ipcRenderer.invoke('overview:open'), // Windows' Task View
  update: (what) => ipcRenderer.invoke(`update:${what === 'check' || what === 'apply' ? what : 'status'}`),
  updateToken: (t) => ipcRenderer.invoke('update:token', t),
  onUpdate: on('update'),
  clips: (what, ...args) => ipcRenderer.invoke(`clip:${['list', 'use', 'copy', 'pin', 'remove', 'clear'].includes(what) ? what : 'list'}`, ...args),
  onClips: on('clips'),
  theme: () => ipcRenderer.invoke('theme:bundle'),
  onTheme: on('theme'),
  themes: (what, ...args) => ipcRenderer.invoke(`themes:${what}`, ...args),
  gallery: (what, ...args) => ipcRenderer.invoke(`gallery:${what}`, ...args),
  desktops: () => ipcRenderer.invoke('desktops'),
  deskCurrent: () => ipcRenderer.invoke('desk:current'),
  winwallKey: (id) => ipcRenderer.invoke('wall:winkey', id),
  wallpaperToWindows: () => ipcRenderer.invoke('wallpaper:toWindows'),
  onSwitching: on('switching'),
  onCursor: on('cursor'),
  onHomeShown: on('home-shown'),
  onHomeHidden: on('home-hidden'),
  onWeatherChanged: on('weather-changed'),
  onApps: on('apps'),
  homeReady: () => ipcRenderer.send('home:ready'),
  searchFiles: (q) => ipcRenderer.invoke('files:search', q),
  recentFiles: () => ipcRenderer.invoke('files:recent'),
  pinPath: (p) => ipcRenderer.invoke('pin:add', p),
  pinFile: (file) => ipcRenderer.invoke('pin:add', webUtils.getPathForFile(file)), // a file dropped on Home
  unpin: (p) => ipcRenderer.invoke('pin:remove', p),
  pinIcon: (p) => ipcRenderer.invoke('pin:icon', p),
  revealPin: (p) => ipcRenderer.invoke('pin:reveal', p),
  dockPin: (exe) => ipcRenderer.invoke('dock:pin', exe),
});
